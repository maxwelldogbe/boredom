"""Build core/content/emoji.json (and the allowed-emoji table) from tools/emoji_src/.

Usage:
    python tools/build_emoji.py [path to Unicode emoji-test.txt, version 13.1]

With an emoji-test.txt, core/content/unicode_emoji.txt is regenerated first: every
fully-qualified emoji up to Emoji 13.1, without skin tones, ZWJ or tag sequences. Without
it, the table already in content/ is used. Sources and licences: core/content/SOURCES.md.

Puzzle sources (all written for this game, except the emoji names and versions from Unicode):
    singles.txt, compounds.txt, phrases.txt, titles.txt, flag_combos.txt: hand-written puzzles;
    countries.txt: country flags and capital-city puzzles (flag + cityscape).
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from games.content_rules import (  # noqa: E402
    CONTENT_DIR,
    MAX_EMOJI_VERSION,
    load_blocklist,
    load_emoji_table,
    parse_emoji,
)
from games.normalize import normalize  # noqa: E402

SOURCES = Path(__file__).resolve().parent / "emoji_src"
PUZZLE_FILES = ("singles.txt", "compounds.txt", "phrases.txt", "titles.txt", "flag_combos.txt")
CITYSCAPE = "\U0001f3d9️"  # 🏙️
SKIN_TONES = range(0x1F3FB, 0x1F400)
ZWJ, TAGS = 0x200D, range(0xE0000, 0xE0080)


def build_table(emoji_test: Path) -> str:
    """The allowed table from Unicode's emoji-test.txt, as `<emoji>\\t<version>\\t<name>` lines."""
    lines = [
        "# Allowed puzzle emoji: fully-qualified, Emoji 13.1 or older, no skin tones, no ZWJ or",
        "# tag sequences. Generated by tools/build_emoji.py from Unicode emoji-test.txt 13.1.",
        "# Copyright (c) 2020 Unicode, Inc. Unicode License; see SOURCES.md.",
    ]
    for raw in emoji_test.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        codes, rest = raw.split(";", 1)
        status, comment = rest.split("#", 1)
        if status.strip() != "fully-qualified":
            continue
        points = [int(c, 16) for c in codes.split()]
        if ZWJ in points or any(p in SKIN_TONES or p in TAGS for p in points):
            continue
        emoji, version, name = comment.strip().split(" ", 2)
        if float(version.lstrip("E")) <= MAX_EMOJI_VERSION:
            lines.append(f"{emoji}\t{version.lstrip('E')}\t{name}")
    return "\n".join(lines) + "\n"


def flag(code: str) -> str:
    return "".join(chr(0x1F1E6 + ord(ch) - ord("A")) for ch in code)


def split_alts(text: str) -> list[str]:
    return [a.strip() for a in text.split(";") if a.strip()]


def read_puzzles(path: Path) -> list[dict]:
    """`emojis | answer | alternatives | difficulty` lines under `# category: X` headers."""
    puzzles, category = [], None
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("# category:"):
            category = line.split(":", 1)[1].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) != 4 or category is None:
            raise SystemExit(f"{path.name}:{number}: expected 4 fields under a category")
        emojis, answer, alts, difficulty = parts
        alternatives = [a for a in split_alts(alts) if normalize(a) != normalize(answer)]
        puzzles.append(
            {
                "emojis": emojis,
                "answer": answer,
                "alternatives": alternatives,
                "category": category,
                "difficulty": difficulty,
            }
        )
    return puzzles


def read_countries(path: Path) -> list[dict]:
    flags, capitals = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        code, name, alts, tier, capital, capital_alts, capital_tier = (
            p.strip() for p in line.split("|")
        )
        flags.append(
            {
                "emojis": flag(code),
                "answer": name,
                "alternatives": split_alts(alts),
                "category": "Flag",
                "difficulty": tier,
            }
        )
        if capital != "-":
            capitals.append(
                {
                    "emojis": flag(code) + CITYSCAPE,
                    "answer": capital,
                    "alternatives": [
                        a for a in split_alts(capital_alts) if normalize(a) != normalize(capital)
                    ],
                    "category": "Capital city",
                    "difficulty": capital_tier,
                }
            )
    return flags + capitals


def check(puzzles: list[dict]) -> list[str]:
    """Problems the loader does not look for: repeated emoji strings and repeated answers."""
    problems, by_emoji, by_answer = [], {}, {}
    for p in puzzles:
        if p["emojis"] in by_emoji:
            problems.append(
                f"same emojis {p['emojis']} for {by_emoji[p['emojis']]!r} and {p['answer']!r}"
            )
        by_emoji[p["emojis"]] = p["answer"]
        key = normalize(p["answer"])
        if key in by_answer:
            problems.append(
                f"answer {p['answer']!r} used twice ({by_answer[key]} and {p['emojis']})"
            )
        by_answer[key] = p["emojis"]
    return problems


def main() -> None:
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    if len(sys.argv) == 2:
        table_path = CONTENT_DIR / "unicode_emoji.txt"
        table_path.write_text(build_table(Path(sys.argv[1])), encoding="utf-8")
        print(f"Wrote {table_path}")
    puzzles = [p for name in PUZZLE_FILES for p in read_puzzles(SOURCES / name)]
    puzzles += read_countries(SOURCES / "countries.txt")
    problems = check(puzzles)
    if problems:
        sys.exit("Fix these in tools/emoji_src/:\n" + "\n".join(f"  - {p}" for p in problems))
    parse_emoji(puzzles, table=load_emoji_table(), blocklist=load_blocklist())
    out = CONTENT_DIR / "emoji.json"
    text = "[\n" + ",\n".join(json.dumps(p, ensure_ascii=False) for p in puzzles) + "\n]\n"
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {len(puzzles)} puzzles to {out}")


if __name__ == "__main__":
    main()
